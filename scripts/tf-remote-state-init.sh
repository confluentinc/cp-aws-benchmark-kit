#!/usr/bin/env bash
# One-shot: bootstrap the TF state S3 bucket + DynamoDB lock table, then
# auto-populate envs/east{1,2}/backend.tf so `terraform init` works immediately.
#
# Idempotent — safe to re-run.
#
# Usage: bash scripts/tf-remote-state-init.sh

set -euo pipefail
REPO_ROOT=$(cd "$(dirname "$0")/.." && pwd)
source "$REPO_ROOT/.env"

BUCKET="${TF_STATE_BUCKET:-cp-benchmark-kit-tfstate-${AWS_ACCOUNT_ID}}"
TABLE="${TF_STATE_TABLE:-cp-benchmark-kit-tfstate-lock}"

echo "[$(date +%H:%M:%S)] TF remote-state bootstrap"
echo "  bucket: $BUCKET"
echo "  table:  $TABLE"

cd "$REPO_ROOT/terraform/remote-state"
terraform init -input=false 2>&1 | tail -3
terraform apply -auto-approve \
  -var "aws_profile=$AWS_PROFILE" \
  -var "region=$REGION1" \
  -var "bucket_name=$BUCKET" \
  -var "table_name=$TABLE" 2>&1 | tail -5

# Auto-wire backend.tf in both envs
for region in east1 east2; do
  case "$region" in
    east1) tf_region="$REGION1" ;;
    east2) tf_region="$REGION2" ;;
  esac
  cat > "$REPO_ROOT/terraform/envs/$region/backend.tf" <<EOF
# Auto-generated by scripts/tf-remote-state-init.sh — do not edit by hand.
# Re-run that script to regenerate after changing bucket/table in .env.

terraform {
  backend "s3" {
    bucket         = "$BUCKET"
    key            = "$region/terraform.tfstate"
    region         = "$tf_region"
    dynamodb_table = "$TABLE"
    encrypt        = true
  }
}
EOF
  echo "  ✓ wrote terraform/envs/$region/backend.tf"
done

echo "✓ Remote state ready. Next: make tf-apply-east1 && make tf-apply-east2"
